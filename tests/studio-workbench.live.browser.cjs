 const page=await browser.newPage({viewport:{width:1440,height:1000}});page.setDefaultTimeout(15000);
 const errors=[],requests=[];page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>requests.push(new URL(r.url()).pathname));
 const origin=process.env.STUDIO_TEST_URL;assert.match(origin,/^http:\/\/(127\.0\.0\.1|localhost):\d+\/?$/);
 assert.equal((await page.request.post(origin+'/api/auth/login',{data:{username:process.env.STUDIO_TEST_USER,password:process.env.STUDIO_TEST_PASSWORD}})).ok(),true);
 const space=(await (await page.request.get(origin+'/api/auth/workspaces')).json()).workspaces[0];
 await page.goto(origin+'/workspaces/'+space.id);
 await page.waitForFunction(()=>document.getElementById('frame-canvas')?.contentWindow.CanvasHome?.ready);
 const frame=page.frames().find(f=>f.url().includes('/static/canvas-home.html'));
 await frame.evaluate(()=>CanvasHome.ready);
 assert.equal(requests.some(path=>/member-canvas-edit|canvas-task-|\/canvas\/classic\/|\/api\/config|page-state|task-results|\/renew/.test(path)),false);
 assert.equal(await frame.evaluate(()=>typeof MemberCanvasEdit),'undefined');
